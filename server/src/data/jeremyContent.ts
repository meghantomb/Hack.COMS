function line(
  conversationId: string,
  node: Omit<
    DialogueNode,
    "conversationId" | "endingType" | "minFriendliness" | "guestCharacterId" | "variantGroup"
  > &
    Partial<
      Pick<
        DialogueNode,
        "conversationId" | "endingType" | "minFriendliness" | "guestCharacterId" | "variantGroup"
      >
    >
): DialogueNode {
  return {
    conversationId,
    endingType: "bad",
    minFriendliness: 0,
    guestCharacterId: null,
    variantGroup: null,
    ...node,
  };
}

function reply(
  option: Omit<
    DialogueOption,
    "minFriendliness" | "continuesConversation" | "minigameId" | "requiredTier" | "requiresMinigameWin"
  > &
    Partial<
      Pick<
        DialogueOption,
        | "minFriendliness"
        | "continuesConversation"
        | "minigameId"
        | "requiredTier"
        | "requiresMinigameWin"
      >
    >
): DialogueOption {
  return {
    minFriendliness: 0,
    continuesConversation: false,
    requiresMinigameWin: false,
    minigameId: null,
    requiredTier: null,
    ...option,
  };
}

/** A visit can continue. The game itself only ends on a real refusal or the last scene. */
function visit(
  conversationId: string,
  node: Omit<Parameters<typeof line>[1], "isEnding" | "endingType"> &
    Partial<Pick<DialogueNode, "isEnding" | "endingType">>
): DialogueNode {
  return line(conversationId, { ...node, isEnding: false, endingType: "bad" });
}

/** A cold goodbye ends the visit. The pond, and the other ducks, stay open. */
function shoreExit(fromId: string): DialogueOption {
  return reply({
    id: `${fromId}_shore`,
    nodeId: fromId,
    text: "Go see who else is on the pond.",
    nextNodeId: "pond_shore",
    friendlinessDelta: 0,
    sortOrder: 0,
  });
}

function visitExit(fromId: string, nextId: string, continueText: string): DialogueOption[] {
  return [
    reply({
      id: `${fromId}_keep`,
      nodeId: fromId,
      text: continueText,
      nextNodeId: nextId,
      friendlinessDelta: 0,
      continuesConversation: true,
      sortOrder: 0,
    }),
    reply({
      id: `${fromId}_shore`,
      nodeId: fromId,
      text: "Go see who else is on the pond.",
      nextNodeId: "pond_shore",
      friendlinessDelta: 0,
      sortOrder: 1,
    }),
  ];
}

